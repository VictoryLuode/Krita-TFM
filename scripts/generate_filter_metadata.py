"""Deterministically generate both public catalogs and native parameter metadata."""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / 'schema/filters.json'


def outputs(schema):
    if schema['schema_version'] != 1:
        raise ValueError('Unsupported filter schema version')
    filters, rows, backend_rows, ids = [], [], [], set()
    cpp_string = lambda value: 'QStringLiteral(' + json.dumps(value, ensure_ascii=False) + ')'
    for entry in schema['filters']:
        fid = entry['id']
        if fid in ids:
            raise ValueError('Duplicate filter: ' + fid)
        ids.add(fid)
        public = {k: v for k, v in entry.items() if k not in ('aliases', 'backends', 'settings')}
        public['settings'] = []
        if entry['backends']['vulkan']:
            public['vulkan'] = True
        seen = set()
        for spec in entry['settings']:
            key, kind = spec['key'], spec['value_type']
            if key in seen:
                raise ValueError('Duplicate parameter: ' + fid + '.' + key)
            seen.add(key)
            if spec.get('catalog', True):
                public['settings'].append({k: v for k, v in spec.items() if k not in
                    ('value_type', 'factory_type', 'override_type', 'catalog')})
            if kind == 'action':
                continue
            default = spec['default']
            choices = [v[0] if isinstance(v, list) else v for v in spec.get('options', [])]
            if choices and default not in choices:
                raise ValueError('Invalid enum default: ' + key)
            if 'min' in spec and not spec['min'] <= default <= spec['max']:
                raise ValueError('Default outside range: ' + key)
            factory_kind = spec.get('factory_type', kind)
            value = (cpp_string(default) if isinstance(default, str) else
                     str(default).lower() if isinstance(default, bool) else
                     repr(float(default)) if factory_kind == 'number' else str(default))
            editable = spec.get('editable', True) and kind in ('number', 'integer', 'bool', 'enum')
            rows.append('        {' + ', '.join([
                cpp_string(fid), cpp_string(key), cpp_string(spec.get('override_type', kind)),
                str(spec.get('min', 0)), str(spec.get('max', 0)), 'QVariant(' + value + ')',
                '{' + ', '.join(map(cpp_string, choices)) + '}', str(editable).lower()]) + '},')
        filters.append(public)
        backend_rows.append('        {' + ', '.join([cpp_string(fid),
            '{' + ', '.join(map(cpp_string, entry['aliases'])) + '}',
            '{' + ', '.join(map(cpp_string, entry['backends']['cpu'])) + '}',
            '{' + ', '.join(map(cpp_string, entry['backends']['vulkan'])) + '}']) + '},')
    py = '# Generated by scripts/generate_filter_metadata.py; edit schema/filters.json.\n'
    py += 'SCHEMA_VERSION = 1\nFILTERS = ' + pprint.pformat(filters, width=110, sort_dicts=False) + '\n'
    py += 'BACKENDS = ' + pprint.pformat({e['id']: e['backends'] for e in schema['filters']}, width=110) + '\n'
    py += 'VULKAN_FILTER_IDS = frozenset(e["id"] for e in FILTERS if e.get("vulkan"))\n'
    py += '''FILTER_DEFAULT_SPECS = {
    entry['id']: [dict(spec) for spec in entry['settings']
                  if spec.get('editable', True) and spec.get('type') != 'action'
                  and ('options' in spec or ('min' in spec and 'max' in spec)
                       or isinstance(spec.get('default'), bool))]
    for entry in FILTERS
}
'''
    header = '''// Generated by scripts/generate_filter_metadata.py; edit schema/filters.json.
#pragma once
#include <QStringList>
#include <QVariant>
#include <QVector>
namespace tfm_metadata {
constexpr int SchemaVersion = 1;
struct Parameter { QString filter, key, type; double min, max; QVariant value; QStringList options; bool editable; };
struct Backend { QString filter; QStringList aliases, cpuDepths, vulkanDepths; };
inline const QVector<Parameter> &parameters() {
    static const QVector<Parameter> value = {
''' + '\n'.join(rows) + '''
    }; return value;
}
inline const QVector<Backend> &backends() {
    static const QVector<Backend> value = {
''' + '\n'.join(backend_rows) + '''
    }; return value;
}
inline QString canonicalId(const QString &id) {
    for (const auto &spec : backends()) if (id == spec.filter || spec.aliases.contains(id)) return spec.filter;
    return id;
}
inline const Parameter *parameter(const QString &id, const QString &key) {
    const QString canonical = canonicalId(id);
    for (const auto &spec : parameters()) if (spec.filter == canonical && spec.key == key) return &spec;
    return nullptr;
}
}
'''
    return {ROOT / 'pykrita/tfm/filters/catalog.py': py,
            ROOT / 'native/fx/src/filter_metadata.h': header}


def generate(check=False):
    generated = outputs(json.loads(SCHEMA.read_text(encoding='utf-8')))
    stale = []
    for path, content in generated.items():
        if path.is_file() and path.read_text(encoding='utf-8') == content:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not check:
            path.write_text(content, encoding='utf-8', newline='\n')
    if check and stale:
        raise ValueError('Stale filter metadata: ' + ', '.join(stale))
    return stale


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print('Filter metadata:', generate(args.check) or 'current')
